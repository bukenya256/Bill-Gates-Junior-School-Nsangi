const assert=require('node:assert/strict'),fs=require('fs'),os=require('os'),path=require('path');
const {Store}=require('./src/core/store');
const {HM,DEFAULTS}=require('./src/core/hm');
const {Cloud}=require('./src/core/cloud');
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'bgs-restore-'));
const hm=new HM(new Store(path.join(dir,'hm.json'),DEFAULTS));
hm.setCurrentTerm(2026,3);
const a=hm.addApplication({first:'Amina',last:'Test',className:'P1',type:'day',paidNow:30000}).student;
const b=hm.addApplication({first:'Brian',last:'Test',className:'P5',type:'boarding',paidNow:30000}).student;
const d=hm.addApplication({first:'Claire',last:'Test',className:'P7',type:'boarding',paidNow:30000}).student;
assert.equal(hm.getState().students.length,3);
assert.throws(()=>hm.recordPromotion({studentId:a.id,year:2026,term:3,decision:'promoted'}),/Record Term 3/);
for(const s of [a,b,d]) hm.acceptMarks([{id:`2026|3|EOT|${s.id}|Mathematics`,studentId:s.id,year:2026,term:3,exam:'EOT',className:s.className,subject:'Mathematics',score:70,at:new Date().toISOString()}]);
hm.recordPromotion({studentId:a.id,year:2026,term:3,decision:'promoted'});
hm.recordPromotion({studentId:b.id,year:2026,term:3,decision:'repeat'});
hm.recordPromotion({studentId:d.id,year:2026,term:3,decision:'promoted'});
assert.equal(hm.d.students[a.id].className,'P1');
hm.setCurrentTerm(2027,1);
assert.equal(hm.d.students[a.id].className,'P2');
assert.equal(hm.d.students[b.id].className,'P5');
assert.equal(hm.d.students[d.id].status,'inactive');
assert.equal(hm.d.students[a.id].classHistory[2026],'P1');
assert.equal(hm.getState().students.find(s=>s.id===a.id).fee.due,250000);
assert.throws(()=>hm.setCurrentTerm(2026,3),/Cannot roll back/);
const su=hm.addDiscipline({studentId:a.id,action:'suspension',reason:'Test incident',date:'2027-02-01',end:'2027-02-10'});
assert.equal(su.end,'2027-02-10');
assert.equal(hm.d.students[a.id].status,'active');
const ex=hm.addDiscipline({studentId:b.id,action:'expulsion',reason:'Test expulsion'});
assert.equal(hm.d.students[b.id].status,'inactive');
assert.equal(Object.keys(hm.d.discipline).length,2);
const cloud=new Cloud(hm,()=>null); cloud.stop();
const rows=[];
for(const col of ['students','staff','payments','bills','salaryBills','marks','comments','discipline','promotions']) for (const [id,data] of Object.entries(hm.d[col])) rows.push({key:`${col}:${id}`,collection:col,data});
rows.push({key:'meta:current',collection:'meta',data:{current:hm.d.meta.current,counters:hm.d.meta.counters,admSeq:hm.d.meta.admSeq}});
rows.push({key:'audit:all',collection:'audit',data:hm.d.audit});
const restored=cloud.buildRecovery(rows);
assert.equal(Object.keys(restored.data.students).length,3);
assert.equal(Object.keys(restored.data.discipline).length,2);
assert.equal(Object.keys(restored.data.promotions).length,3);
assert.equal(Object.keys(restored.data.payments).length,3);
assert.deepEqual(restored.data.meta.current,{year:2027,term:1});
assert.throws(()=>cloud.buildRecovery([]),/no complete student/);
assert.throws(()=>cloud.buildRecovery([...rows,rows.find(x=>x.key.startsWith('payments:'))]),/Duplicate/);
fs.rmSync(dir,{recursive:true,force:true});
console.log('recovery/promotion/discipline OK');
